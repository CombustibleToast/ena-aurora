using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._AS.DeviceLinking;
using Content.Shared._AS.DeviceLinking.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._AS.DeviceLinking.UI;

/// <summary>
/// Interface for the signal console.
/// Only outputs with at least one device link are displayed.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SignalConsoleWindow : FancyWindow
{
    public const string EditorCardStyleClass = "SignalConsoleEditorCard";
    public const string MutedLabelStyleClass = "SignalConsoleMuted";

    private SignalConsoleBoundUserInterfaceState? _lastState;
    private bool _editMode;

    public event Action<int>? OnToggle;
    public event Action<int>? OnPulse;
    public event Action<int, string>? OnRename;
    public event Action<int, SignalConsoleChannelMode>? OnModeChanged;

    public SignalConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        EditButton.OnPressed += _ =>
        {
            _editMode = !_editMode;
            EditButton.Text = Loc.GetString(_editMode ? "signal-console-done" : "signal-console-edit");
            RebuildChannels();
        };
    }

    public void UpdateState(SignalConsoleBoundUserInterfaceState state)
    {
        _lastState = state;
        RebuildChannels();
    }

    private void RebuildChannels()
    {
        if (_lastState == null)
            return;

        var state = _lastState;
        Channels.RemoveAllChildren();
        var linkedCount = state.Linked.Count(linked => linked);
        EditButton.Visible = linkedCount > 0;
        EditButton.ReservesSpace = false;
        ChannelScroll.Visible = linkedCount > 0;
        EmptyState.Visible = linkedCount == 0;

        if (linkedCount == 0)
            return;

        for (var i = 0; i < state.Linked.Count; i++)
        {
            if (state.Linked[i])
            {
                Channels.AddChild(_editMode ? CreateEditorCard(i, state) : CreateActionCard(i, state));
            }
        }
    }

    private Control CreateActionCard(int channel, SignalConsoleBoundUserInterfaceState state)
    {
        var isToggle = state.Modes[channel] == SignalConsoleChannelMode.Toggle;
        var active = isToggle && state.States[channel];
        var card = new SignalConsoleChannelButton(active);
        card.OnPressed += _ =>
        {
            if (isToggle)
                OnToggle?.Invoke(channel);
            else
                OnPulse?.Invoke(channel);
        };

        card.SetDisplay(
            state.Labels[channel],
            Loc.GetString(isToggle ? state.States[channel] ? "signal-console-toggle-on" : "signal-console-toggle-off" : "signal-console-pulse-action"),
            Loc.GetString("signal-console-channel-corner", ("channel", channel + 1)));
        return card;
    }

    private Control CreateEditorCard(int channel, SignalConsoleBoundUserInterfaceState state)
    {
        var card = new PanelContainer
        {
            HorizontalExpand = true,
            MinHeight = 150,
        };
        card.AddStyleClass(EditorCardStyleClass);
        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 8,
            Margin = new Thickness(12),
        };
        card.AddChild(content);
        var channelDetail = new Label
        {
            Text = Loc.GetString("signal-console-channel-detail", ("channel", channel + 1)),
        };
        channelDetail.AddStyleClass(MutedLabelStyleClass);
        content.AddChild(channelDetail);
        var renameRow = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 4,
        };
        var name = new LineEdit
        {
            Text = state.Labels[channel],
            PlaceHolder = Loc.GetString("signal-console-name-placeholder"),
            IsValid = text => text.Length <= SignalConsoleComponent.MaximumLabelLength,
            HorizontalExpand = true,
        };
        name.OnTextChanged += _ =>
        {
            if (name.Text.Length <= SignalConsoleComponent.MaximumLabelLength)
                return;

            name.Text = name.Text[..SignalConsoleComponent.MaximumLabelLength];
            name.CursorPosition = SignalConsoleComponent.MaximumLabelLength;
        };
        var save = new Button { Text = Loc.GetString("signal-console-save"), MinWidth = 58 };
        name.OnTextEntered += args => OnRename?.Invoke(channel, args.Text);
        save.OnPressed += _ => OnRename?.Invoke(channel, name.Text);
        renameRow.AddChild(name);
        renameRow.AddChild(save);
        content.AddChild(renameRow);

        var modeRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        modeRow.AddChild(new Label
        {
            Text = Loc.GetString("signal-console-button-type"),
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
        });
        var mode = new OptionButton { MinWidth = 112 };
        mode.AddItem(Loc.GetString("signal-console-mode-pulse"), (int) SignalConsoleChannelMode.Pulse);
        mode.AddItem(Loc.GetString("signal-console-mode-toggle"), (int) SignalConsoleChannelMode.Toggle);
        mode.SelectId((int) state.Modes[channel]);
        mode.OnItemSelected += args =>
        {
            args.Button.SelectId(args.Id);
            OnRename?.Invoke(channel, name.Text);
            OnModeChanged?.Invoke(channel, (SignalConsoleChannelMode) args.Id);
        };
        modeRow.AddChild(mode);
        content.AddChild(modeRow);
        return card;
    }

}
