using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._AS.DeviceLinking.UI;

[GenerateTypedNameReferences]
public sealed partial class SignalConsoleChannelButton : ContainerButton
{
    public const string ActiveStyleClass = "SignalConsoleActive";
    public const string NameStyleClass = "SignalConsoleName";
    public const string ActionStyleClass = "SignalConsoleAction";
    public const string CornerStyleClass = "SignalConsoleCorner";

    public SignalConsoleChannelButton(bool active)
    {
        RobustXamlLoader.Load(this);
        if (active)
            AddStyleClass(ActiveStyleClass);
    }

    public void SetDisplay(string name, string action, string channel)
    {
        ChannelName.Text = name;
        ActionText.Text = action;
        CornerLabel.Text = channel;
    }

}
