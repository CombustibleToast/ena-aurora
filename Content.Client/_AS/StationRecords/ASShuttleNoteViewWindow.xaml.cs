using Content.Shared.StationRecords;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._AS.StationRecords;

[GenerateTypedNameReferences]
public sealed partial class ASShuttleNoteViewWindow : DefaultWindow
{
    public ASShuttleNoteViewWindow(ShuttleRecordNoteView note, string formattedTime)
    {
        RobustXamlLoader.Load(this);
        NoteTitle.Text = note.Title;
        NoteMetadata.Text = $"{note.Author} - {formattedTime}";
        NoteBody.SetMessage(FormattedMessage.FromUnformatted(note.Description));
        NoteCloseButton.OnPressed += _ => Close();
    }
}
