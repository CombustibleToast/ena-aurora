using System.Linq;
using Content.Shared.StationRecords;
using Content.Shared.StatusIcon;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._AS.StationRecords;

[GenerateTypedNameReferences]
public sealed partial class ASGeneralStationRecordConsoleWindow : DefaultWindow
{
    [Dependency] private IPrototypeManager _prototypeManager = null!;
    [Dependency] private IEntityManager _entityManager = null!;

    public Action<uint?>? OnKeySelected;

    public Action<StationRecordFilterType, string>? OnFiltersChanged;
    public Action<uint>? OnDeleted;

    public event Action<int, string, string>? OnShuttleNoteAdded;
    public event Action<int, int>? OnShuttleNoteDeleted;
    public event Action<uint, int>? OnShuttleCrewUpdated;
    public event Action<uint>? OnShuttleCrewRestored;
    public event Action<uint, string>? OnShuttleCrewArchived; // Owner archive reason
    private bool _isPopulating;
    private ShuttleCrewRecordView? _selectedCrew;
    private int? _selectedProfileId;
    private List<ShuttleRecordNoteView>? _shuttleNotes;
    private bool _canCreateShuttleNotes;
    private int? _viewingArchivedProfile;
    private GeneralStationRecordConsoleState? _lastState;
    private bool _viewerCanManage;
    private HashSet<int> _deletableNoteIds = [];

    private StationRecordFilterType _currentFilterType;

    public ASGeneralStationRecordConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _currentFilterType = StationRecordFilterType.Name;

        RecordsTabs.SetTabTitle(0, Loc.GetString("general-station-record-console-tab-records"));
        RecordsTabs.SetTabTitle(1, Loc.GetString("general-station-record-console-tab-applicants"));
        CrewTabs.SetTabTitle(0, Loc.GetString("general-station-record-console-crew-tab-active"));
        CrewTabs.SetTabTitle(1, Loc.GetString("general-station-record-console-crew-tab-archived"));
        CrewTabs.TabsVisible = false;
        CrewTabs.SetTabVisible(1, false);
        NewShuttleNoteButton.OnPressed += _ => OpenNewNoteDialog();
        InitializeApplicantsPanel();

        foreach (var item in Enum.GetValues<StationRecordFilterType>())
        {
            StationRecordsFilterType.AddItem(GetTypeFilterLocals(item), (int)item);
        }

        RecordListing.OnItemSelected += args =>
        {
            if (_isPopulating || RecordListing[args.ItemIndex].Metadata is not uint cast)
                return;

            _viewingArchivedProfile = null;
            OnKeySelected?.Invoke(cast);
        };

        RecordListing.OnItemDeselected += _ =>
        {
            if (!_isPopulating)
                OnKeySelected?.Invoke(null);
        };

        StationRecordsFilterType.OnItemSelected += eventArgs =>
        {
            var type = (StationRecordFilterType)eventArgs.Id;

            if (_currentFilterType != type)
            {
                _currentFilterType = type;
                FilterListingOfRecords();
            }
        };

        StationRecordsFiltersValue.OnTextEntered += args =>
        {
            FilterListingOfRecords(args.Text);
        };

        StationRecordsFilters.OnPressed += _ =>
        {
            FilterListingOfRecords(StationRecordsFiltersValue.Text);
        };

        StationRecordsFiltersReset.OnPressed += _ =>
        {
            StationRecordsFiltersValue.Text = "";
            FilterListingOfRecords();
        };

        ArchivedRecordListing.OnItemSelected += args =>
        {
            if (_isPopulating || ArchivedRecordListing[args.ItemIndex].Metadata is not ShuttleCrewRecordView crew)
                return;
            _selectedCrew = crew;
            _viewingArchivedProfile = crew.ProfileId;
            PopulateArchivedRecord(crew);
        };

    }

    public void UpdateState(GeneralStationRecordConsoleState state)
    {
        _lastState = state;
        if (state.ShuttleCrew != null)
        {
            foreach (var crew in state.ShuttleCrew)
                crew.CanManage = _viewerCanManage;
        }

        if (state.ShuttleNotes != null)
        {
            foreach (var note in state.ShuttleNotes)
                note.CanDelete = _deletableNoteIds.Contains(note.Id);
        }

        _shuttleNotes = state.ShuttleNotes; // Apply after resolving the selected person.
        _canCreateShuttleNotes = state.CanCreateShuttleNotes;
        PopulateShuttleCrew(state.ShuttleCrew); // Active/Archived crew tabs
        if (state.Filter != null)
        {
            if (state.Filter.Type != _currentFilterType)
                _currentFilterType = state.Filter.Type;

            if (state.Filter.Value != StationRecordsFiltersValue.Text)
                StationRecordsFiltersValue.Text = state.Filter.Value;
        }

        StationRecordsFilterType.SelectId((int)_currentFilterType);

        RefreshApplicantsPanel(state);

        if (_viewingArchivedProfile is { } archivedProfile && state.ShuttleCrew?.FirstOrDefault(x => x.ProfileId == archivedProfile && x.ArchiveReason.HasValue) is { } archivedCrew)
        {
            PopulateArchivedRecord(archivedCrew);
            return;
        }

        if (state.RecordListing == null)
        {
            RecordPortraitContainer.RemoveAllChildren(); // No record, no portrait.
            RecordHeaderContainer.RemoveAllChildren();
            RecordContainer.RemoveAllChildren();
            RecordListingStatus.Visible = true;
            RecordListing.Visible = true;
            RecordListingStatus.Text = Loc.GetString("general-station-record-console-empty-state");
            RecordContainer.Visible = true;
            RecordContainerStatus.Visible = true;
            PopulateShuttleNotes(null);
            return;
        }

        RecordListingStatus.Visible = false;
        RecordListing.Visible = true;
        RecordContainer.Visible = true;
        PopulateRecordListing(state.RecordListing!, state.SelectedKey, state.ShuttleCrew);

        RecordContainerStatus.Visible = state.Record == null;

        if (state.Record != null)
        {
            RecordContainerStatus.Visible = state.SelectedKey == null;
            RecordContainerStatus.Text = state.SelectedKey == null
                ? Loc.GetString("general-station-record-console-no-record-found")
                : Loc.GetString("general-station-record-console-select-record-info");
            // Removal buttons only appear for registered ACTIVE records
            var canDelete = state.CanDeleteEntries && state.SelectedKey != state.ShuttleOwnerStationRecordId;
            var selectedCrew = state.ShuttleCrew?.FirstOrDefault(x => !x.ArchiveReason.HasValue && x.StationRecordId == state.SelectedKey);
            PopulateRecordContainer(state.Record, canDelete, state.SelectedKey, selectedCrew);
        }
        else
        {
            RecordContainer.RemoveAllChildren();
            RecordPortraitContainer.RemoveAllChildren();
            RecordHeaderContainer.RemoveAllChildren();
            PopulateShuttleNotes(null);
        }
    }

    /// Applies permissions sent specifically for this viewer, separate from the console's shared UI state.
    public void ApplyViewerPermissions(ShuttleRecordViewerPermissions permissions)
    {
        _viewerCanManage = permissions.CanManage;
        _deletableNoteIds = permissions.DeletableNoteIds;
        if (_lastState != null)
            UpdateState(_lastState);
    }
    private void PopulateRecordListing(Dictionary<uint, string> listing, uint? selected, List<ShuttleCrewRecordView>? crew)
    {
        RecordListing.Clear();
        RecordListing.ClearSelected();

        _isPopulating = true;

        foreach (var (key, name) in listing)
        {
            // If they are SSD, show the SSD icon. If they are active, show nothing. If they are archived, show nothing.
            var isSsd = crew?.Any(x => !x.ArchiveReason.HasValue && x.StationRecordId == key && x.Presence == ShuttleCrewPresence.SSD) == true;
            Texture? ssdIcon = null;
            if (isSsd && _prototypeManager.TryIndex<SsdIconPrototype>($"SSDIcon", out var iconPrototype))
                ssdIcon = _entityManager.System<SpriteSystem>().Frame0(iconPrototype.Icon);

            var member = crew?.FirstOrDefault(x => !x.ArchiveReason.HasValue && x.StationRecordId == key);
            var ownerMarker = member?.IsShuttleOwner == true ? "★ " : string.Empty;
            var cryoMarker = member?.Presence == ShuttleCrewPresence.Cryo ? "❄ " : string.Empty;
            var displayName = $"{ownerMarker}{cryoMarker}{name}"; // Snowflake marks someone in cryosleep.
            var item = RecordListing.AddItem(displayName, ssdIcon, iconScale: 2f); // Star marks shuttle owner
            item.Metadata = key;
            item.Selected = key == selected;
        }

        _isPopulating = false;

        RecordListing.SortItemsByText();
    }

    private void PopulateRecordContainer(GeneralStationRecord record, bool enableDelete, uint? id, ShuttleCrewRecordView? crew)
    {
        RecordContainer.RemoveAllChildren();
        var newRecord = new ASGeneralRecord(record, enableDelete, id, _prototypeManager, crew);
        newRecord.OnDeletePressed = crew is { CanManage: true, ArchiveReason: null }
            ? OpenArchiveReasonDialog
            : OnDeleted; // Owner archives require an entered reason.
        newRecord.OnCrewUpdated = OnShuttleCrewUpdated;
        newRecord.OnCrewRestored = OnShuttleCrewRestored;
        _selectedCrew = crew;
        _selectedProfileId = crew?.ProfileId ?? record.ProfileId;
        PopulateShuttleNotes(_selectedProfileId);
        AttachRecordView(newRecord);
    }

    private void AttachRecordView(ASGeneralRecord record)
    {
        RecordPortraitContainer.RemoveAllChildren();
        RecordHeaderContainer.RemoveAllChildren();
        record.PortraitPanel.Orphan();
        record.RecordHeader.Orphan();
        RecordPortraitContainer.AddChild(record.PortraitPanel);
        RecordHeaderContainer.AddChild(record.RecordHeader);
        RecordContainer.AddChild(record);
    }

    private void FilterListingOfRecords(string text = "")
    {
        if (!_isPopulating)
            OnFiltersChanged?.Invoke(_currentFilterType, text);
    }

    private string GetTypeFilterLocals(StationRecordFilterType type)
    {
        return Loc.GetString($"general-station-record-{type.ToString().ToLower()}-filter");
    }

}
