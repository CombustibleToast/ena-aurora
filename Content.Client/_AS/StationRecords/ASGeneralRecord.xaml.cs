using Content.Shared._NF.ShuttleRecords;
using Content.Shared.Humanoid.Prototypes;
using Content.Shared.Preferences;
using Content.Shared.Roles;
using Content.Shared.StationRecords;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

// Intentional to extend its partial type.
namespace Content.Client._AS.StationRecords;

[GenerateTypedNameReferences]
public sealed partial class ASGeneralRecord : Control
{
    public Action<uint>? OnDeletePressed;
    public Action<uint, int>? OnCrewUpdated;
    public Action<uint>? OnCrewRestored;

    public ASGeneralRecord(GeneralStationRecord record, bool canDelete, uint? id, IPrototypeManager prototypeManager, ShuttleCrewRecordView? crew = null)
    {
        RobustXamlLoader.Load(this);
        FieldsContainer.ItemMargins = new Thickness(0);
        PortraitStaticBackground.ShaderOverride = prototypeManager.Index<ShaderPrototype>($"ASStatic").Instance().Duplicate();
        RecordName.Text = record.Name;
        Pronouns.Text = Loc.GetString(record.Gender switch // Collect my pronouns
        {
            Robust.Shared.Enums.Gender.Male => "humanoid-profile-editor-pronouns-male-text",
            Robust.Shared.Enums.Gender.Female => "humanoid-profile-editor-pronouns-female-text",
            Robust.Shared.Enums.Gender.Epicene => "humanoid-profile-editor-pronouns-epicene-text",
            _ => "humanoid-profile-editor-pronouns-neuter-text",
        });
        Age.Text = record.Age.ToString();
        Title.Text = Loc.GetString(record.JobTitle);
        var species = Loc.GetString(prototypeManager.Index<SpeciesPrototype>(record.Species).Name);
        if (record.Replicant)
            species = Loc.GetString("species-name-replicant", ("species", species));
        Species.Text = species;
        Gender.Text = record.Gender.ToString();
        Fingerprint.Text = record.Fingerprint ?? Loc.GetString("generic-not-available-shorthand");
        Dna.Text = record.DNA ?? Loc.GetString("generic-not-available-shorthand");

        if (record.Appearance != null)
        {
            var previewProfile = new HumanoidCharacterProfile
            {
                Name = record.Name,
                Species = record.Species,
                Age = record.Age,
                Appearance = record.Appearance.Clone(),
            }.WithSex(record.Sex).WithGender(record.Gender);

            // Render with loadout selection if available
            if (record.SelectedLoadout != null)
                previewProfile = previewProfile.WithLoadout(record.SelectedLoadout);

            prototypeManager.TryIndex<JobPrototype>(record.JobPrototype, out var jobPrototype);
            CharacterPreview.LoadPreview(previewProfile, jobPrototype);
        }
        else
        {
            CharacterPreview.Visible = false;
            NoPhotoLabel.Visible = true; // If no appearance is available, "NO PHOTO AVAILABLE"
        }

        if (crew != null)
        {
            DurationRow.Visible = !crew.ArchiveReason.HasValue && !crew.IsShuttleOwner;
            DurationEdit.Text = crew.ExpiresAt is { } expiry
                ? Math.Max(1, (int) Math.Ceiling((expiry - crew.RegisteredAt).TotalMinutes)).ToString()
                : "0"; // if no expiry, set to 0
            DurationEdit.Editable = crew.CanManage;
            RegisteredRow.Visible = true;
            RegisteredAt.Text = FormatTime(crew.RegisteredAt);

            if (!crew.ArchiveReason.HasValue && !crew.IsShuttleOwner)
            {
                var submittedMinutes = int.TryParse(DurationEdit.Text, out var initialMinutes) ? initialMinutes : 0;
                void SubmitDuration(string text)
                {
                    if (!int.TryParse(text, out var minutes))
                        return;

                    minutes = Math.Max(0, minutes);
                    if (minutes == submittedMinutes)
                        return;

                    submittedMinutes = minutes;
                    OnCrewUpdated?.Invoke(crew.StationRecordId, minutes);
                }

                DurationEdit.OnTextEntered += args => SubmitDuration(args.Text);
                DurationEdit.OnFocusExit += args => SubmitDuration(args.Text);
            }
            else if (crew.ArchiveReason.HasValue)
            {
                ArchivedRow.Visible = true;
                ArchivedAt.Text = FormatTime(crew.ArchivedAt ?? TimeSpan.Zero);
                ArchivedByRow.Visible = true;
                ArchivedBy.Text = crew.ArchivedBy ?? Loc.GetString("general-station-record-console-unknown");
                ArchiveReasonRow.Visible = true;
                ArchiveReason.Text = crew.ArchiveDetails ?? crew.ArchiveReason switch
                {
                    ShuttleCrewArchiveReason.SelfRemoved => Loc.GetString("general-station-record-console-archive-self-removed"),
                    ShuttleCrewArchiveReason.OwnerRemoved => Loc.GetString("general-station-record-console-archive-owner-removed"),
                    ShuttleCrewArchiveReason.Expired => Loc.GetString("general-station-record-console-archive-registration-expired"),
                    ShuttleCrewArchiveReason.CharacterDeleted => Loc.GetString("general-station-record-console-archive-character-deleted"),
                    _ => Loc.GetString("general-station-record-console-archive-system"),
                };
                RestoreButton.Visible = crew is { CanManage: true, OwnerRestoreBlocked: false };
                RestoreButton.OnPressed += _ => OnCrewRestored?.Invoke(crew.StationRecordId);
            }
        }

        var ownerCanArchive = crew is { CanManage: true, IsShuttleOwner: false, ArchiveReason: null }; // Owners cannot archive themselves.
        var canShowDelete = crew == null ? canDelete : ownerCanArchive;
        if (canShowDelete && id != null)
        {
            DeleteButton.Visible = true;
            if (crew != null)
                DeleteButton.Text = Loc.GetString("general-station-record-console-archive-action");
            DeleteButton.OnPressed += _ => OnDeletePressed?.Invoke(id.Value);
        }
    }

    private static string FormatTime(TimeSpan time)
    {
        return $"{(int)time.TotalHours:00}:{time.Minutes:00}:{time.Seconds:00}";
    }
}
