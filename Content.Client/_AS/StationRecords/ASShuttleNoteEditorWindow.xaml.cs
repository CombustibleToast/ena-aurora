using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._AS.StationRecords;

[GenerateTypedNameReferences]
public sealed partial class ASShuttleNoteEditorWindow : DefaultWindow
{
    private const int MaxTitleLength = 30;
    private const int MaxBodyLength = 1000;

    public event Action<string, string>? OnSaved;

    public ASShuttleNoteEditorWindow()
    {
        RobustXamlLoader.Load(this);
        NoteBody.Placeholder = new Rope.Leaf(Loc.GetString("general-station-record-console-note-body-placeholder"));
        NoteTitle.OnTextChanged += _ => UpdateSaveButton();
        NoteBody.OnTextChanged += args =>
        {
            var text = Rope.Collapse(args.TextRope);
            if (text.Length > MaxBodyLength)
                NoteBody.TextRope = new Rope.Leaf(text[..MaxBodyLength]);
            UpdateSaveButton();
        };
        CancelButton.OnPressed += _ => Close();
        SaveButton.OnPressed += _ => Save();
        UpdateSaveButton();
    }

    private void UpdateSaveButton()
    {
        SaveButton.Disabled = string.IsNullOrWhiteSpace(NoteTitle.Text) ||
                              NoteTitle.Text.Length > MaxTitleLength ||
                              string.IsNullOrWhiteSpace(Rope.Collapse(NoteBody.TextRope));
    }

    private void Save()
    {
        var title = NoteTitle.Text.Trim();
        var body = Rope.Collapse(NoteBody.TextRope).Trim();
        if (title.Length is < 1 or > MaxTitleLength || body.Length is < 1 or > MaxBodyLength)
            return;

        OnSaved?.Invoke(title, body);
        Close();
    }
}
